export function textValue(value: unknown): string {
  if (value === null || value === undefined || typeof value === 'object') return m.noValue;
  return String(value);
}
export function statusText(status: unknown): string {
  return (
    ({ draft: m.draft, published: m.published, completed: m.completed } as Record<string, string>)[String(status)] ??
    textValue(status)
  );
}
