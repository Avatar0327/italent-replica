const PERSON: Record<StatutoryGroup, { gender: string; identityType: string | null }> = {
  male: { gender: 'male', identityType: null },
  female_cadre: { gender: 'female', identityType: '20' },
  female_worker: { gender: 'female', identityType: '10' },
};

const nextMonth = (value: string): string => {
  const total = Number(value.slice(0, 4)) * 12 + Number(value.slice(5)); // 0 基月序 + 1
  return `${String(Math.floor(total / 12)).padStart(4, '0')}-${String((total % 12) + 1).padStart(2, '0')}`;
};

describe('AC-RT-16 法定对照表逐段边界（独立夹具，审查 P2-1）', () => {
  it('夹具自检：每组 37 / 37 / 61 行；组内相邻行首尾相接；年龄逐段 +1 个月、封顶后年龄不再增加', () => {
    const counts = { male: 37, female_cadre: 37, female_worker: 61 };
    for (const group of Object.keys(counts) as StatutoryGroup[]) {
      const rows = ROWS.filter((row) => row[0] === group);
      expect(rows).toHaveLength(counts[group]);
      rows.forEach((row, index) => {
        if (index === 0) return;
        const previous = rows[index - 1]!;
        expect(row[1]).toBe(nextMonth(previous[2]));
        expect(row[3] * 12 + row[4]).toBe(previous[3] * 12 + previous[4] + 1);
      });
    }
  });

  it.each(ROWS.map((row) => [`${row[0]} ${row[1]}～${row[2]}`, ...row] as const))(
    '%s：段首月、段末月的改革后年龄与预计退休日期',
    (_label, group, first, last, years, months, expectedFirst, expectedLast) => {
      const { gender, identityType } = PERSON[group];
      for (const [birthMonth, expected] of [
        [first, expectedFirst],
        [last, expectedLast],
      ] as const) {
        const birthday = `${birthMonth}-15`;
        expect(statutoryRetirementAge(group, birthday), `${group} ${birthMonth} 年龄`).toEqual({ years, months });
        expect(statutoryExpectedDate(birthday, gender, identityType), `${group} ${birthMonth} 预计日期`).toBe(expected);
      }
    },
  );
});
